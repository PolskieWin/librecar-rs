fun stringsFor(lang: AppLang): CarStrings {
    val usePolish = when (lang) {
        AppLang.PL -> true
        AppLang.EN -> false
        AppLang.AUTO -> Locale.getDefault().language.lowercase().startsWith("pl")
    }
    return if (usePolish) PolishStrings else EnglishStrings
}

